import React, { useEffect, useState } from 'react';
import { View, Text, StyleSheet, ActivityIndicator } from 'react-native';
import { useLocalSearchParams } from 'expo-router';
import { useTheme } from '../../hooks/useTheme';
import { StorageService } from '../../services/storage';
import { Order } from '../../types';
import { formatMoney } from '../../utils/currency';
import { FONT_SIZES, SPACING } from '../../constants/theme';

export default function OrderDetailScreen() {
  const { id } = useLocalSearchParams<{ id: string }>();
  const { colors } = useTheme();
  const [order, setOrder] = useState<Order | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    (async () => {
      const orders = await StorageService.getOrders();
      const found = orders.find((o) => o.id === id) || null;
      setOrder(found);
      setLoading(false);
    })();
  }, [id]);

  if (loading) {
    return (
      <View style={[styles.center, { backgroundColor: colors.background }]}>
        <ActivityIndicator color={colors.primary} />
      </View>
    );
  }

  if (!order) {
    return (
      <View style={[styles.center, { backgroundColor: colors.background }]}>
        <Text style={{ color: colors.textSecondary }}>Order not found</Text>
      </View>
    );
  }

  return (
    <View style={[styles.container, { backgroundColor: colors.background }]}>
      <View style={[styles.card, { backgroundColor: colors.card }]}>
        <Text style={[styles.label, { color: colors.textSecondary }]}>Order ID</Text>
        <Text style={[styles.value, { color: colors.text }]}>{order.id}</Text>

        <Text style={[styles.label, { color: colors.textSecondary }]}>Amount</Text>
        <Text style={[styles.amount, { color: colors.primary }]}>
          {formatMoney(order.amount, order.currency)}
        </Text>

        <Text style={[styles.label, { color: colors.textSecondary }]}>Items</Text>
        <Text style={[styles.value, { color: colors.text }]}>{order.itemCount}</Text>

        <Text style={[styles.label, { color: colors.textSecondary }]}>Status</Text>
        <Text style={[styles.value, { color: colors.text }]}>{order.status}</Text>

        <Text style={[styles.label, { color: colors.textSecondary }]}>Created</Text>
        <Text style={[styles.value, { color: colors.text }]}>
          {new Date(order.createdAt).toLocaleString()}
        </Text>

        <Text style={[styles.label, { color: colors.textSecondary }]}>Source</Text>
        <Text style={[styles.value, { color: colors.text }]}>{order.source}</Text>
      </View>
      <Text style={[styles.note, { color: colors.textSecondary }]}>
        This is a simulated local order generated by PulsePay. It does not represent a real
        transaction.
      </Text>
    </View>
  );
}

const styles = StyleSheet.create({
  container: { flex: 1, padding: SPACING.lg },
  center: { flex: 1, justifyContent: 'center', alignItems: 'center' },
  card: { borderRadius: 16, padding: SPACING.xl },
  label: { fontSize: FONT_SIZES.sm, marginTop: 16, marginBottom: 2 },
  value: { fontSize: FONT_SIZES.md, fontWeight: '500' },
  amount: { fontSize: 28, fontWeight: '700' },
  note: { fontSize: FONT_SIZES.xs, marginTop: 20, lineHeight: 18, textAlign: 'center' },
});
